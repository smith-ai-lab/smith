#!/bin/sh
# Tests of bootstrap/, the committed lowering of the .smith sources that smith's own build compiles. Usage: sh
# tests/bootstrap.sh path/to/smith. Each file says where it is from; the smith under test lowers its source to the same
# bytes (also in a hostile environment, and the stage0, which has no clang, writes the same); and the C compiles under
# every C23 compiler of the machine (the system's clang, the `cc` that builds smith), with no help from smith.
set -u
case $1 in /*) smith=$1 ;; *) smith=$(pwd)/$1 ;; esac
here=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT INT TERM
failures=0

expect() { # name, status (0 is ok)
    if [ "$2" = 0 ]; then
        echo "ok    $1"
    else
        failures=$((failures + 1))
        echo "FAIL  $1"
    fi
}

cd "$here" || exit 1
files=$(find bootstrap -name '*.c' | LC_ALL=C sort)
[ -n "$files" ]
expect "bootstrap/ holds files" $?

# The stage0: a C23 compiler and smith.c, no clang inside.
cc -std=gnu23 smith.c -o "$work/stage0" 2>"$work/stage0.err"
expect "the stage0 builds with one cc command" $?

for file in $files; do
    rel=${file#bootstrap/}
    src=${rel%.c}.smith
    first=$(head -n 1 "$file")
    [ "$first" = "// Generated by smith from $src. Do not edit; run smith build bootstrap." ]
    expect "$file: first line says it is generated, and from $src" $?

    lower() { # environment words (unquoted), then the program
        envw=$1
        shift
        $envw sh scripts/bootstrap.sh "$@" "$src" "$work/lowered.c" && cat "$work/lowered.c"
    }
    lower "" "$smith" >"$work/full.c" 2>"$work/full.err"
    cmp -s "$work/full.c" "$file"
    expect "$file: is what $src lowers to" $?

    lower "" "$work/stage0" >"$work/zero.c" 2>"$work/zero.err"
    cmp -s "$work/zero.c" "$file"
    expect "$file: the stage0 lowers $src to the same bytes" $?

    # Nothing of the machine is read: no SDK, no include path, no environment.
    lower "env -i PATH=/usr/bin:/bin SDKROOT=/nonexistent CPATH=/nonexistent C_INCLUDE_PATH=/nonexistent" "$smith" \
        >"$work/hostile.c" 2>"$work/hostile.err"
    cmp -s "$work/hostile.c" "$file"
    expect "$file: the lowering reads nothing of the machine (no SDK, no environment)" $?

    ! grep -q -e '^module ' -e '^export ' -e '^import ' -e '\[\[smith::' "$file"
    expect "$file: no .smith syntax is left" $?

    for compiler in /usr/bin/clang cc; do
        command -v "$compiler" >/dev/null 2>&1 || continue
        "$compiler" -std=gnu23 -Wall -Wextra -Wpedantic -Werror -I include -fsyntax-only "$file" 2>"$work/cc.err"
        expect "$file: compiles with $compiler -std=gnu23 -Wpedantic -Werror" $?
    done
done

# The directives of a module stay as written, in place, and the stage0 writes the same bytes.
mkdir -p "$work/demo"
cat >"$work/demo/dir.smith" <<'EOF'
module demo::dir;
#pragma STDC FP_CONTRACT OFF
#ifdef __FAST_MATH__
#error "no -ffast-math"
#endif
#if defined(__x86_64__)
export u32 f(u32 x) { return x + 1; }
#elif defined(__aarch64__)
export u32 f(u32 x) { return x + 2; }
#else
#error "unsupported"
#endif
EOF
(cd "$work" && "$smith" cc --smith-lower demo/dir.smith >full.c 2>full.err; "$work/stage0" cc --smith-lower demo/dir.smith >zero.c 2>zero.err)
grep -q '^#pragma STDC FP_CONTRACT OFF$' "$work/full.c" && grep -q '^#error "unsupported"$' "$work/full.c" &&
    grep -q '^#elif defined(__aarch64__)$' "$work/full.c" && grep -q '^#endif$' "$work/full.c"
expect "directives of a module are kept, with every branch lowered" $?
cmp -s "$work/full.c" "$work/zero.c"
expect "the stage0 keeps the same directives" $?
printf 'module demo::mac;\n#define W u32\nexport u32 g(void) { return 1; }\n' >"$work/demo/mac.smith"
(cd "$work" && "$smith" cc --smith-lower demo/mac.smith >/dev/null 2>mac.err)
[ $? = 1 ] && grep -q 'demo/mac.smith:2:11: error: a macro that uses' "$work/mac.err"
expect "a #define with a sized type is an error at its line" $?

echo "bootstrap: $failures failure(s)"
[ "$failures" = 0 ]
