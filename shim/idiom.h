// ---- Reading a file's tokens ---------------------------------------------------------------------------------------

struct Lexed {
    std::vector<Token> tokens;
    std::vector<bool> in_directive; // the token is on a preprocessor directive's line
};

inline Lexed lex(const SourceManager &sm, const LangOptions &options, FileID file) {
    Lexed result;
    llvm::StringRef text = sm.getBufferData(file);
    Lexer lexer(sm.getLocForStartOfFile(file), options, text.begin(), text.begin(), text.end());
    Token token;
    bool directive = false;
    for (;;) {
        lexer.LexFromRawLexer(token);
        if (token.is(tok::eof)) break;
        if (token.isAtStartOfLine()) directive = token.is(tok::hash);
        result.tokens.push_back(token);
        result.in_directive.push_back(directive);
    }
    return result;
}

inline bool is_name(const Token &token, llvm::StringRef name) {
    return token.is(tok::raw_identifier) && token.getRawIdentifier() == name;
}

inline bool is_smith_file(const SourceManager &sm, FileID file) {
    OptionalFileEntryRef entry = sm.getFileEntryRefForID(file);
    return entry && entry->getName().ends_with(".smith");
}

// A header smith generated from a module: its text is the module's, and the module's own file is what is judged.
inline bool is_generated(const SourceManager &sm, FileID file) {
    return sm.getBufferData(file).substr(0, 200).contains("Generated by smith");
}

// ---- smith-sized-types ----------------------------------------------------------------------------------------------

inline const char *sized_type(llvm::StringRef name) {
    static const std::map<std::string, const char *> table = {
        {"uint8_t", "u8"},  {"uint16_t", "u16"}, {"uint32_t", "u32"}, {"uint64_t", "u64"}, {"int8_t", "i8"},
        {"int16_t", "i16"}, {"int32_t", "i32"},  {"int64_t", "i64"},  {"size_t", "usize"}, {"ptrdiff_t", "isize"},
    };
    auto found = table.find(name.str());
    return found == table.end() ? nullptr : found->second;
}

// The sized type for a run of C's integer keywords (`unsigned long long`): empty for `char` alone, which stays char.
inline std::string sized_integer(const std::vector<std::string> &run) {
    int longs = 0;
    bool is_unsigned = false, is_signed = false, is_short = false, is_char = false, is_double = false, is_float = false;
    for (const std::string &word : run) {
        if (word == "long") longs++;
        if (word == "double") is_double = true;
        if (word == "float") is_float = true;
        if (word == "unsigned") is_unsigned = true;
        if (word == "signed") is_signed = true;
        if (word == "short") is_short = true;
        if (word == "char") is_char = true;
    }
    if (is_double) return "f64";
    if (is_float) return "f32";
    if (is_char) return is_unsigned ? "u8" : is_signed ? "i8" : "";
    if (is_short) return is_unsigned ? "u16" : "i16";
    if (longs > 0) return is_unsigned ? "u64" : "i64";
    return is_unsigned ? "u32" : "i32";
}

class SizedTypesCheck final : public ClangTidyCheck {
  public:
    SizedTypesCheck(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    void registerPPCallbacks(const SourceManager &SM, Preprocessor *PP, Preprocessor *) override {
        PP->addPPCallbacks(std::make_unique<Callbacks>(*this, SM, *PP));
    }

  private:
    class Callbacks final : public PPCallbacks {
      public:
        Callbacks(SizedTypesCheck &check, const SourceManager &sm, Preprocessor &pp) : check(check), sm(sm), pp(pp) {}

        void EndOfMainFile() override {
            FileID main = sm.getMainFileID();
            if (!is_smith_file(sm, main)) return;
            Lexed lexed = lex(sm, pp.getLangOpts(), main);
            const std::vector<Token> &tokens = lexed.tokens;
            std::set<size_t> allowed = main_signature(tokens);
            for (size_t i = 0; i < tokens.size(); i++) {
                if (lexed.in_directive[i] || !tokens[i].is(tok::raw_identifier)) continue;
                if (i > 0 && (tokens[i - 1].is(tok::period) || tokens[i - 1].is(tok::arrow))) continue;
                llvm::StringRef name = tokens[i].getRawIdentifier();
                if (const char *sized = sized_type(name)) {
                    report(tokens[i], name.str(), sized);
                    continue;
                }
                if (!is_keyword(name)) continue;
                std::vector<std::string> run;
                size_t j = i;
                while (j < tokens.size() && !lexed.in_directive[j] && tokens[j].is(tok::raw_identifier) &&
                       is_keyword(tokens[j].getRawIdentifier())) {
                    run.push_back(tokens[j].getRawIdentifier().str());
                    j++;
                }
                bool ok =
                    j < tokens.size() && is_name(tokens[j], "_BitInt"); // `unsigned _BitInt(128)` has no sized name
                for (size_t k = i; k < j; k++)
                    ok = ok || allowed.count(k) > 0;
                std::string sized = sized_integer(run);
                if (!sized.empty() && !ok) report(tokens[i], join(run), sized);
                i = j - 1;
            }
        }

      private:
        SizedTypesCheck &check;
        const SourceManager &sm;
        Preprocessor &pp;

        static bool is_keyword(llvm::StringRef name) {
            return name == "unsigned" || name == "signed" || name == "short" || name == "long" || name == "int" ||
                   name == "char" || name == "float" || name == "double";
        }

        static std::string join(const std::vector<std::string> &words) {
            std::string result;
            for (const std::string &word : words)
                result += (result.empty() ? "" : " ") + word;
            return result;
        }

        // `int` is C's own spelling in `int main(int argc, char **argv)`: the return type and the parameters.
        static std::set<size_t> main_signature(const std::vector<Token> &tokens) {
            std::set<size_t> allowed;
            for (size_t i = 1; i + 1 < tokens.size(); i++) {
                if (!is_name(tokens[i], "main") || !tokens[i + 1].is(tok::l_paren)) continue;
                if (is_name(tokens[i - 1], "int")) allowed.insert(i - 1);
                int depth = 0;
                for (size_t j = i + 1; j < tokens.size(); j++) {
                    if (tokens[j].is(tok::l_paren)) depth++;
                    if (tokens[j].is(tok::r_paren) && --depth == 0) break;
                    allowed.insert(j);
                }
            }
            return allowed;
        }

        void report(const Token &token, const std::string &spelled, const std::string &sized) {
            check.diag(token.getLocation(),
                       "`%0` is a C type, and a .smith file has the sized types: write `%1` (u8 u16 u32 u64, i8 i16 "
                       "i32 i64, usize, isize, f32, f64)")
                << spelled << sized;
        }
    };
};

// ---- smith-module-library -------------------------------------------------------------------------------------------

// A library that is a module has `// smith-module: smith::arena` in its generated header, and `// smith-names:
// push_raw= smith_arena_push ...` pairs the module's names with the C names. Headers are read as the file includes
// them.
struct ModuleHeader {
    std::string module;
    std::string binding;
    std::map<std::string, std::string> c_names; // C name -> the module's name
    std::set<std::string> generics;             // the module's generic functions
};

inline bool parse_module_header(llvm::StringRef text, ModuleHeader &out) {
    bool found = false;
    for (int line = 0; line < 4096 && !text.empty(); line++) {
        llvm::StringRef current;
        std::tie(current, text) = text.split('\n');
        if (line >= 8 && !current.starts_with("// smith-generic: ")) continue;
        if (current.consume_front("// smith-generic: ")) {
            std::istringstream words(current.str());
            std::string module, member;
            if (words >> module >> member) out.generics.insert(member);
        } else if (current.consume_front("// smith-module: ")) {
            out.module = current.str();
            out.binding = current.substr(current.rfind(':') + 1).str();
            found = true;
        } else if (current.consume_front("// smith-names: ")) {
            std::istringstream words(current.str());
            std::string word;
            while (words >> word) {
                size_t equals = word.find('=');
                if (equals != std::string::npos) out.c_names[word.substr(equals + 1)] = word.substr(0, equals);
            }
        }
    }
    return found;
}

class ModuleLibraryCheck final : public ClangTidyCheck {
  public:
    ModuleLibraryCheck(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    void registerPPCallbacks(const SourceManager &SM, Preprocessor *PP, Preprocessor *) override {
        PP->addPPCallbacks(std::make_unique<Callbacks>(*this, SM, *PP));
    }

  private:
    class Callbacks final : public PPCallbacks {
      public:
        Callbacks(ModuleLibraryCheck &check, const SourceManager &sm, Preprocessor &pp)
            : check(check), sm(sm), pp(pp) {}

        void InclusionDirective(SourceLocation, const Token &, llvm::StringRef FileName, bool, CharSourceRange,
                                OptionalFileEntryRef File, llvm::StringRef, llvm::StringRef, const Module *, bool,
                                SrcMgr::CharacteristicKind) override {
            if (!File || !is_smith_file(sm, sm.getMainFileID())) return;
            auto buffer = pp.getFileManager().getBufferForFile(*File);
            ModuleHeader header;
            if (!buffer || !parse_module_header((*buffer)->getBuffer(), header)) return;
            by_name[FileName.str()] = header;
        }

        void EndOfMainFile() override {
            FileID main = sm.getMainFileID();
            if (!is_smith_file(sm, main) || by_name.empty()) return;
            Lexed lexed = lex(sm, pp.getLangOpts(), main);
            const std::vector<Token> &tokens = lexed.tokens;
            for (size_t i = 0; i + 2 < tokens.size(); i++) {
                if (is_name(tokens[i], "import") && tokens[i + 1].is(tok::less)) header(tokens, i);
                if (is_name(tokens[i], "c") && tokens[i + 1].is(tok::coloncolon) &&
                    tokens[i + 2].is(tok::raw_identifier))
                    name(tokens[i + 2]);
            }
            by_name.clear();
        }

      private:
        ModuleLibraryCheck &check;
        const SourceManager &sm;
        Preprocessor &pp;
        std::map<std::string, ModuleHeader> by_name;

        void header(const std::vector<Token> &tokens, size_t i) {
            size_t end = i + 2;
            while (end < tokens.size() && !tokens[end].is(tok::greater) && !tokens[end].isAtStartOfLine())
                end++;
            if (end >= tokens.size() || !tokens[end].is(tok::greater)) return;
            llvm::StringRef text = sm.getBufferData(sm.getMainFileID());
            unsigned from = sm.getFileOffset(tokens[i + 1].getLocation()) + 1;
            unsigned to = sm.getFileOffset(tokens[end].getLocation());
            std::string written = text.substr(from, to - from).str();
            auto found = by_name.find(written);
            if (found == by_name.end()) return;
            check.diag(tokens[i].getLocation(),
                       "`import <%0>;` reads %1, a module, through its C header: write `import %1;` and call it as "
                       "`%2::name(...)`%3")
                << written << found->second.module << found->second.binding << example(found->second);
        }

        void name(const Token &token) {
            llvm::StringRef spelled = token.getRawIdentifier();
            for (const auto &entry : by_name) {
                const ModuleHeader &module = entry.second;
                auto found = module.c_names.find(spelled.str());
                if (found == module.c_names.end()) continue;
                check.diag(token.getLocation(),
                           "`c::%0` is `%2::%3` of the module %1, reached through its C header: write `import %1;` "
                           "and `%2::%3`%4")
                    << spelled << module.module << module.binding << found->second
                    << (example(module) + generic_of(module, found->second));
                return;
            }
        }

        static std::string example(const ModuleHeader &module) {
            if (module.module == "smith::arena") return " (a typed push is `arena::push(&a, T)`)";
            return "";
        }

        // `check_equal_i32` is the named instance of the generic `check_equal` for one type: the call to write is the
        // generic's, which infers the type from its arguments.
        static std::string generic_of(const ModuleHeader &module, const std::string &name) {
            static const char *const types[] = {"bool", "char", "i8",  "i16",   "i32", "i64", "isize",   "u8",
                                                "u16",  "u32",  "u64", "usize", "f32", "f64", "pointer", "ptr"};
            for (const char *type : types) {
                std::string suffix = std::string("_") + type;
                if (name.size() <= suffix.size() ||
                    name.compare(name.size() - suffix.size(), suffix.size(), suffix) != 0)
                    continue;
                std::string base = name.substr(0, name.size() - suffix.size());
                if (module.generics.count(base) != 0) {
                    return " (or, better, the generic `" + module.binding + "::" + base +
                           "(a, b)`, which infers the type from its arguments)";
                }
            }
            return "";
        }
    };
};

// ---- smith-bounded-loop ---------------------------------------------------------------------------------------------

class BoundedLoopCheck final : public ClangTidyCheck {
  public:
    BoundedLoopCheck(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    bool isLanguageVersionSupported(const LangOptions &options) const override {
        return !options.CPlusPlus; // the checks are for C and .smith
    }

    void registerMatchers(ast_matchers::MatchFinder *Finder) override {
        using namespace ast_matchers;
        auto outside_main = unless(hasAncestor(functionDecl(isMain())));
        Finder->addMatcher(forStmt(outside_main).bind("for"), this);
        Finder->addMatcher(whileStmt(outside_main).bind("while"), this);
        Finder->addMatcher(doStmt(outside_main).bind("do"), this);
    }

    void check(const ast_matchers::MatchFinder::MatchResult &Result) override {
        const SourceManager &sm = *Result.SourceManager;
        const Stmt *loop = nullptr;
        const char *spelled = "";
        bool unbounded = false;
        if (const auto *f = Result.Nodes.getNodeAs<ForStmt>("for")) {
            loop = f;
            spelled = f->getCond() == nullptr ? "`for (;;)`" : "a `for` with a constant condition";
            unbounded = f->getCond() == nullptr || always(f->getCond(), *Result.Context);
        } else if (const auto *w = Result.Nodes.getNodeAs<WhileStmt>("while")) {
            loop = w;
            spelled = "a `while` with a constant condition";
            unbounded = always(w->getCond(), *Result.Context);
        } else if (const auto *d = Result.Nodes.getNodeAs<DoStmt>("do")) {
            loop = d;
            spelled = "a `do ... while` with a constant condition";
            unbounded = always(d->getCond(), *Result.Context);
        }
        if (loop == nullptr || !unbounded) return;
        if (sm.isInSystemHeader(sm.getExpansionLoc(loop->getBeginLoc())) || sm.isInSystemMacro(loop->getBeginLoc()))
            return;
        if (!seen.insert(sm.getExpansionLoc(loop->getBeginLoc()).getRawEncoding()).second) return;
        diag(loop->getBeginLoc(),
             "%0 never ends on its own: bound the loop by a count (`for (usize i = 0; i < limit; i++)`); only `main` "
             "runs forever")
            << spelled;
    }

    void onEndOfTranslationUnit() override {
        seen.clear();
    }

  private:
    std::set<unsigned> seen; // a generic's instances are copies of one source

    static bool always(const Expr *condition, const ASTContext &context) {
        bool value = false;
        return !condition->isValueDependent() && condition->EvaluateAsBooleanCondition(value, context) && value;
    }
};

// ---- smith-c23 ------------------------------------------------------------------------------------------------------

inline const char *standard_attribute(llvm::StringRef name) {
    name.consume_front("__");
    name.consume_back("__");
    if (name == "noreturn") return "[[noreturn]]";
    if (name == "unused") return "[[maybe_unused]]";
    if (name == "warn_unused_result") return "[[nodiscard]]";
    if (name == "deprecated") return "[[deprecated]]";
    if (name == "fallthrough") return "[[fallthrough]]";
    return nullptr;
}

class C23Check final : public ClangTidyCheck {
  public:
    C23Check(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    void registerPPCallbacks(const SourceManager &SM, Preprocessor *PP, Preprocessor *) override {
        PP->addPPCallbacks(std::make_unique<Callbacks>(*this, SM, *PP));
    }

    bool isLanguageVersionSupported(const LangOptions &options) const override {
        return !options.CPlusPlus; // the checks are for C and .smith
    }

    void registerMatchers(ast_matchers::MatchFinder *Finder) override {
        using namespace ast_matchers;
        Finder->addMatcher(initListExpr().bind("list"), this);
    }

    // `= {0}` initializes a whole record or array to zero: C23 writes `= {}`.
    void check(const ast_matchers::MatchFinder::MatchResult &Result) override {
        const SourceManager &sm = *Result.SourceManager;
        const auto *list = Result.Nodes.getNodeAs<InitListExpr>("list");
        if (list->isSemanticForm() && list->getSyntacticForm() != nullptr) list = list->getSyntacticForm();
        if (list->getNumInits() != 1 || list->getLBraceLoc().isInvalid() || sm.isInSystemHeader(list->getBeginLoc()))
            return; // an invalid brace is the list that brace elision made
        if (!list->getType()->isRecordType() && !list->getType()->isConstantArrayType()) return;
        const auto *zero = dyn_cast<IntegerLiteral>(list->getInit(0)->IgnoreParenImpCasts());
        if (zero == nullptr || !zero->getValue().isZero()) return;
        if (!seen.insert(sm.getExpansionLoc(list->getBeginLoc()).getRawEncoding()).second) return;
        diag(list->getBeginLoc(), "`{0}` is C's way to zero a whole object: write `{}`");
    }

    void onEndOfTranslationUnit() override {
        seen.clear();
    }

  private:
    std::set<unsigned> seen;

    class Callbacks final : public PPCallbacks {
      public:
        Callbacks(C23Check &check, const SourceManager &sm, Preprocessor &pp) : check(check), sm(sm), pp(pp) {}

        void FileChanged(SourceLocation Loc, FileChangeReason Reason, SrcMgr::CharacteristicKind FileType,
                         FileID) override {
            if (Reason != EnterFile || FileType != SrcMgr::C_User) return;
            FileID file = sm.getFileID(Loc);
            if (file.isValid() && !is_generated(sm, file)) files.push_back(file);
        }

        void EndOfMainFile() override {
            if (pp.getLangOpts().CPlusPlus) return;
            for (FileID file : files)
                scan(file);
            files.clear();
        }

      private:
        C23Check &check;
        const SourceManager &sm;
        Preprocessor &pp;
        std::vector<FileID> files;

        void scan(FileID file) {
            Lexed lexed = lex(sm, pp.getLangOpts(), file);
            const std::vector<Token> &tokens = lexed.tokens;
            for (size_t i = 0; i < tokens.size(); i++) {
                if (!tokens[i].is(tok::raw_identifier)) continue;
                llvm::StringRef name = tokens[i].getRawIdentifier();
                bool member = i > 0 && (tokens[i - 1].is(tok::period) || tokens[i - 1].is(tok::arrow));
                if (member) continue;
                if (name == "NULL" && !conditional_directive(lexed, i)) {
                    check.diag(tokens[i].getLocation(), "`NULL` is a macro: write `nullptr`");
                } else if (name == "_Bool") {
                    check.diag(tokens[i].getLocation(), "`_Bool` is C99's spelling: write `bool`, a keyword in C23");
                } else if (name == "_Static_assert" || name == "_Alignas" || name == "_Alignof") {
                    std::string keyword = name.drop_front(1).lower();
                    check.diag(tokens[i].getLocation(), "`%0` is C11's spelling: write `%1`, a keyword in C23")
                        << name << llvm::StringRef(keyword);
                } else if (name == "_Noreturn") {
                    check.diag(tokens[i].getLocation(), "`_Noreturn` is C11's spelling: write `[[noreturn]]`");
                } else if (name == "stdbool" && i + 1 < tokens.size() && tokens[i + 1].is(tok::period)) {
                    check.diag(tokens[i].getLocation(),
                               "`<stdbool.h>` is not needed: `bool`, `true` and `false` are keywords in C23");
                } else if (name == "__attribute__") {
                    attribute(tokens, i);
                }
            }
        }

        static bool conditional_directive(const Lexed &lexed, size_t i) {
            if (!lexed.in_directive[i]) return false;
            size_t start = i;
            while (start > 0 && lexed.in_directive[start - 1])
                start--;
            if (start + 1 >= lexed.tokens.size()) return false;
            llvm::StringRef directive = lexed.tokens[start + 1].is(tok::raw_identifier)
                                            ? lexed.tokens[start + 1].getRawIdentifier()
                                            : llvm::StringRef();
            return directive == "ifdef" || directive == "ifndef" || directive == "undef" || directive == "if" ||
                   directive == "elif" || directive == "include";
        }

        // `__attribute__((noreturn, unused))`: each name that has a standard spelling.
        void attribute(const std::vector<Token> &tokens, size_t i) {
            if (i + 2 >= tokens.size() || !tokens[i + 1].is(tok::l_paren) || !tokens[i + 2].is(tok::l_paren)) return;
            int depth = 0;
            for (size_t j = i + 1; j < tokens.size(); j++) {
                if (tokens[j].is(tok::l_paren)) depth++;
                if (tokens[j].is(tok::r_paren) && --depth == 0) break;
                if (depth != 2 || !tokens[j].is(tok::raw_identifier)) continue;
                if (!tokens[j - 1].is(tok::l_paren) && !tokens[j - 1].is(tok::comma)) continue;
                if (const char *standard = standard_attribute(tokens[j].getRawIdentifier()))
                    check.diag(tokens[j].getLocation(), "`__attribute__((%0))` has a standard spelling: write `%1`")
                        << tokens[j].getRawIdentifier() << standard;
            }
        }
    };
};

// ---- smith-constexpr ------------------------------------------------------------------------------------------------

class ConstexprCheck final : public ClangTidyCheck {
  public:
    ConstexprCheck(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    bool isLanguageVersionSupported(const LangOptions &options) const override {
        return !options.CPlusPlus; // the checks are for C and .smith
    }

    void registerMatchers(ast_matchers::MatchFinder *Finder) override {
        using namespace ast_matchers;
        Finder->addMatcher(varDecl(hasGlobalStorage(), hasInitializer(expr()), unless(isImplicit())).bind("variable"),
                           this);
    }

    void check(const ast_matchers::MatchFinder::MatchResult &Result) override {
        const SourceManager &sm = *Result.SourceManager;
        ASTContext &context = *Result.Context;
        const auto *var = Result.Nodes.getNodeAs<VarDecl>("variable");
        if (!var->isFileVarDecl() || var->isConstexpr() || var->getStorageClass() == SC_Extern) return;
        if (!var->isThisDeclarationADefinition() || var->getTLSKind() != VarDecl::TLS_None) return;
        // A constexpr object has internal linkage and is not emitted unless used, so a C object that another file may
        // reach (external linkage: a header's `extern const`) stays const. In a .smith file an export says it, and a
        // private name is the module's.
        bool smith_file = is_smith_file(sm, sm.getMainFileID());
        if (!smith_file && var->getFormalLinkage() != Linkage::Internal) return;
        if (var->getPreviousDecl() != nullptr) return;
        if (sm.isInSystemHeader(var->getLocation()) || sm.isInSystemMacro(var->getLocation())) return;
        if (!var->getType().isConstQualified() || !constexpr_type(var->getType(), context, 0)) return;
        if (!var->getInit()->isConstantInitializer(context, false)) return;
        if (!seen.insert(sm.getExpansionLoc(var->getLocation()).getRawEncoding()).second) return;
        diag(var->getLocation(), "`const` %0 `%1` has a constant initializer: write `constexpr`")
            << (var->getType()->isArrayType() ? "array" : "object") << var->getName();
    }

    void onEndOfTranslationUnit() override {
        seen.clear();
    }

  private:
    std::set<unsigned> seen;

    // What C23's `constexpr` can hold: arithmetic and enumerations, nullptr_t, and arrays and records of them. A
    // floating type is left out, since `constexpr` refuses a value that is not exact in its type.
    static bool constexpr_type(QualType type, ASTContext &context, int depth) {
        if (depth > 4) return false;
        type = type.getCanonicalType();
        if (const ArrayType *array = context.getAsArrayType(type))
            return constexpr_type(array->getElementType(), context, depth + 1);
        if (type->isFloatingType()) return false;
        if (type->isIntegralOrEnumerationType() || type->isNullPtrType()) return true;
        if (const RecordDecl *record = type->getAsRecordDecl()) {
            if (!record->isCompleteDefinition()) return false;
            for (const FieldDecl *field : record->fields()) {
                if (field->isBitField() || !constexpr_type(field->getType(), context, depth + 1)) return false;
            }
            return true;
        }
        return false;
    }
};

// ---- smith-designated-init ------------------------------------------------------------------------------------------

// `{"src/base", fast}` for a struct another module (or header) defines is positional: when the struct gains a field,
// the values shift or the compiler warns at every such site. Naming the fields (`{.path = "src/base", .fast = fast}`)
// is a change the other module cannot break. A struct the file defines itself, a system header's struct and an
// initializer of one value are left alone.
class DesignatedInitCheck final : public ClangTidyCheck {
  public:
    DesignatedInitCheck(llvm::StringRef Name, ClangTidyContext *Context) : ClangTidyCheck(Name, Context) {}

    bool isLanguageVersionSupported(const LangOptions &options) const override {
        return !options.CPlusPlus; // the check is for .smith
    }

    void registerMatchers(ast_matchers::MatchFinder *Finder) override {
        using namespace ast_matchers;
        Finder->addMatcher(initListExpr().bind("list"), this);
    }

    void check(const ast_matchers::MatchFinder::MatchResult &Result) override {
        const SourceManager &sm = *Result.SourceManager;
        if (!is_smith_file(sm, sm.getMainFileID())) return;
        const auto *list = Result.Nodes.getNodeAs<InitListExpr>("list");
        const InitListExpr *written =
            list->isSemanticForm() && list->getSyntacticForm() != nullptr ? list->getSyntacticForm() : list;
        if (written->getNumInits() < 2) return;
        SourceLocation at = written->getBeginLoc();
        if (!at.isValid() || at.isMacroID() || sm.getFileID(at) != sm.getMainFileID()) return;
        for (const Expr *init : written->inits()) {
            if (isa<DesignatedInitExpr>(init)) return;
        }
        const RecordDecl *record = list->getType().getCanonicalType()->getAsRecordDecl();
        if (record == nullptr || !record->isStruct()) return;
        SourceLocation defined = sm.getFileLoc(record->getLocation());
        if (!defined.isValid() || sm.isInSystemHeader(defined) || sm.getFileID(defined) == sm.getMainFileID()) return;
        if (!seen.insert(at.getRawEncoding()).second) return; // a generic's instances are copies of one source
        std::string name = record->getName().str();
        if (name.empty()) {
            if (const TypedefNameDecl *typedef_name = record->getTypedefNameForAnonDecl()) {
                name = typedef_name->getName().str();
            }
        }
        diag(at, "this initializes `%0`, which another file defines, by position: name the fields (`{.field = value, "
                 "...}`), so that a field added to it cannot shift the values")
            << name;
    }

    void onEndOfTranslationUnit() override {
        seen.clear();
    }

  private:
    std::set<unsigned> seen;
};

